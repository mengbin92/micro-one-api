  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('security-center.png'),fullPage:true});
  await page.getByRole('button', { name: '设置双重认证', exact: true }).click();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: '设置双重认证', exact: true }).click();
  await page.getByLabel('当前密码', { exact: true }).fill('password123');
  await page.getByRole('button', { name: '验证并继续' }).click();
  await expect(page.locator('#security-center code')).toBeVisible();
  await page.locator('#security-center').getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: '设置双重认证', exact: true }).click();
  await expect(page.getByRole('link', { name: '在验证器应用中打开' })).toHaveAttribute('href', /^otpauth:\/\/totp\/.+/);
  const secret = (await page.locator('#security-center code').textContent())!;
  await page.getByLabel('验证器验证码').fill(totp(secret));
  await page.getByRole('button', { name: '验证并启用' }).click();
  await expect(page.getByRole('dialog', { name: '保存恢复码' })).toBeVisible();
  const recoveryCodes = (await page.getByRole('dialog').locator('pre').textContent())!.trim().split('\n');
  expect(recoveryCodes).toHaveLength(10);
  expect(await page.evaluate(() => localStorage.getItem('token'))).toBeNull();
  await page.getByRole('button', { name: '已保存，重新登录' }).click();
  await page.getByLabel('用户名', { exact: true }).fill(username);
  await page.getByLabel('密码', { exact: true }).fill('password123');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('button', { name: '返回登录', exact: true }).click();
  await page.getByLabel('密码', { exact: true }).fill('password123');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByLabel('验证码或恢复码').fill('invalid-recovery-code');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('验证码无效、过期或已使用');
  await page.getByLabel('验证码或恢复码').fill(recoveryCodes[0]);
  expect(await page.evaluate(() => localStorage.getItem('token'))).toBeNull();
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto('/tokens');
  await page.getByRole('button', { name: '创建 Token', exact: true }).click();
  await page.getByLabel('Token 名称').fill('browser-step-up');
  await page.getByRole('button', { name: '创建', exact: true }).click();
  await page.getByLabel('验证码或恢复码').fill(recoveryCodes[1]);
  await page.getByRole('button', { name: '验证并继续' }).click();
  await expect(page.locator('#created-token-key')).toHaveValue(/.+/);
  await page.getByRole('button', { name: '完成', exact: true }).click();
  await expect(page.getByText('browser-step-up', { exact: true })).toBeVisible();
  await page.goto('/profile');
  await page.getByRole('button', { name: '重新生成恢复码', exact: true }).click();
  const rotated = (await page.getByRole('dialog', { name: '保存恢复码' }).locator('pre').textContent())!.trim().split('\n');
